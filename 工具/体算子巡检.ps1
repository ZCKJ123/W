$fail = 0
$checked = 0
$sections = @(
    @{n = '灰'; t = "依赖 体库`r`n依赖 体算法`r`n依赖 容量层`r`n将 体 变成 体新建(6, 6, 6)"; calls = $灰; pre = '体写(体, 1, 1, 1, 80)'},
    @{n = '彩'; t = "依赖 体库`r`n依赖 体算法`r`n依赖 容量层`r`n将 体 变成 体新建彩色(6, 6, 6)"; calls = $彩; pre = '体写(体, 1, 1, 1, 80)'},
