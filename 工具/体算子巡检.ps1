$fail = 0
$checked = 0
foreach ($case in @(@{n = '灰'; t = '将 体 变成 体新建(6, 6, 6)'; calls = $灰}, @{n = '彩'; t = '将 体 变成 体新建彩色(6, 6, 6)'; calls = $彩})) {
    foreach ($call in $case.calls) {
        $checked++
        $src = $case.t + "`r`n体写(体, 1, 1, 1, 80)`r`n" + $call + "`r`n"
        $f = Join-Path $dir ('巡检.wen')
        [IO.File]::WriteAllText($f, $src, (New-Object Text.UTF8Encoding($false)))
        $out = & $exe $f 2>&1 | Out-String
        $code = $LASTEXITCODE
        if ($code -ne 0) {
            if ($code -lt 0 -or $code -gt 1000) {
                $fail++
                Write-Host ("崩溃：" + $case.n + "  " + $call + "  （退出码 " + $code + "）")
            } elseif ($out -notmatch '【(运行时|静态|语法|编译)错误】') {
                $fail++
                Write-Host ("失败：" + $case.n + "  " + $call + "  （退出码 " + $code + "）")
            }
        }
    }
}
if ($fail -gt 0) { Write-Host ("体算子巡检：{0} 项有问题" -f $fail); exit 1 }
Write-Host ("体算子巡检：灰度/彩色各一遍，共 {0} 项，无崩溃" -f $checked)
exit 0
